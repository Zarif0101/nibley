'use strict';
// Builds marks.js: hand-drawn pen paths (via library/tools/draw.js, seeded so rebuilds are identical)
// plus the lecturer's block and ground drawings. Run: node gen-marks.js
const fs = require('fs');
const path = require('path');
const D = require('../../../library/tools/draw.js');
const A = path.join(__dirname, '../../../library/assets');

const pathsOf = (svg) => [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
const make = (name, strokes, wobble = 1) => pathsOf(D.toSvg({ name, strokes, wobble }));

// Ring: starts ~10 o'clock, overshoots (draw.js default), radius jitter from the seed.
const ring = (name, cx, cy, rx, ry, rot = 0) => make(name, [D.ellipse(cx, cy, rx, ry, { rot })]);

// Arrow: one bend of ~8% of the length, short open head (second stroke).
function arrow(name, x1, y1, x2, y2, head = 26, bend = 0.08, wobble = 1) {
  const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy);
  const nx = -dy / len, ny = dx / len;
  const mid = [(x1 + x2) / 2 + nx * len * bend, (y1 + y2) / 2 + ny * len * bend];
  const ang = Math.atan2(y2 - mid[1], x2 - mid[0]);
  const w = (s) => [x2 - head * Math.cos(ang + s * 0.5), y2 - head * Math.sin(ang + s * 0.5)];
  return make(name, [D.curve([[x1, y1], mid, [x2, y2]]), D.poly([w(1), [x2, y2], w(-1)])], wobble);
}

const M = {
  // video 1 slide (900 x 560): block centre x 380, floor y 500
  v1_ring: ring('v1-ring', 380, 394, 204, 134, 2),
  v1_up: arrow('v1-up', 320, 292, 324, 206, 26, 0.08),
  v1_weight: arrow('v1-weight', 380, 398, 380, 484, 22, 0.06, 0.5),
  // video 2 slide (900 x 500): block centre x 330, floor y 440
  v2_weight: arrow('v2-weight', 330, 372, 330, 436, 18, 0.06, 0.5),
  v2_up: arrow('v2-up', 330, 298, 332, 190, 22, 0.05, 0.5),
  v2_ring_arrow: ring('v2-ring-arrow', 331, 244, 46, 84, 1),
  v2_ring_floor: ring('v2-ring-floor', 330, 442, 150, 30, 0),
  v2_ring_weight: ring('v2-ring-weight', 330, 404, 34, 56, 0),
  // end card underline (drawn 800 wide, stretched to the url width)
  underline: make('underline', [D.line(0, 0, 800, 0)]),
};
const out = `// generated by gen-marks.js: do not edit\nwindow.MARKS=${JSON.stringify(M)};\nwindow.BLOCK=${JSON.stringify(pathsOf(fs.readFileSync(path.join(A, 'block.svg'), 'utf8'))[0])};\nwindow.GROUND=${JSON.stringify(pathsOf(fs.readFileSync(path.join(A, 'ground.svg'), 'utf8'))[0])};\n`;
fs.writeFileSync(path.join(__dirname, 'marks.js'), out);
console.log('marks.js', out.length, 'bytes');
